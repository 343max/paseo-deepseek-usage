// Regenerates client/deepseek-icon-data.ts from icon.svg.
//
// The plugin's sidebar row cannot use icon.svg directly: Paseo renders plugin SVGs only for
// provider and usage-source branding, a contributed icon is a Lucide name or a component, and
// the plugin client runtime has no SVG renderer or asset loader. So the mark is rasterised once
// here into a PNG the sidebar row can tint.
//
// Needs rsvg-convert on PATH (librsvg). Run with `npm run icon`.

import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const WIDTH = 128;
const CHUNK = 100;
const root = join(import.meta.dirname, "..");
const target = join(root, "client", "deepseek-icon-data.ts");

const svgPath = join(root, "icon.svg");
const svg = await readFile(svgPath, "utf8");
const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1].trim().split(/\s+/).map(Number);
if (!viewBox || viewBox.length !== 4) throw new Error("icon.svg has no usable viewBox");
const [, , viewWidth, viewHeight] = viewBox;
const height = Math.round((WIDTH * viewHeight) / viewWidth);

const directory = await mkdtemp(join(tmpdir(), "deepseek-icon-"));
const pngPath = join(directory, "icon.png");
try {
  execFileSync("rsvg-convert", ["-w", String(WIDTH), "-h", String(height), svgPath, "-o", pngPath]);
  const base64 = (await readFile(pngPath)).toString("base64");
  const chunks = base64.match(new RegExp(`.{1,${CHUNK}}`, "g")) ?? [];
  const literal = chunks
    .map((chunk, index) => `${index === 0 ? "  " : "  + "}"${chunk}"`)
    .join("\n");

  await writeFile(
    target,
    `// Generated by scripts/build-deepseek-icon.mjs from icon.svg. Do not edit by hand;
// run \`npm run icon\` after changing the source SVG.
//
// A data URI rather than an import: the plugin client bundler has no loader for image files.

export const DEEPSEEK_ICON_DATA_URI =
  "data:image/png;base64," +
${literal};
`,
  );
  console.log(`Wrote ${target} (${WIDTH}x${height}, ${base64.length} base64 chars)`);
} finally {
  await rm(directory, { recursive: true, force: true });
}
